"""
router.py  —  route test traffic straight to the Sock Shop backend services

WHY
---
The generated tests call the paths in each service's OpenAPI specification
(e.g. POST /customers/{id}/addresses, POST /carts/{id}/items) at
http://127.0.0.1. On a stock deployment that address is the edge-router,
which forwards everything to the front-end, and the front-end only exposes
the routes the web shop uses. The specified backend routes are therefore
refused ("Cannot POST ...") before any request reaches the service under test.

This tool temporarily replaces the edge-router on port 80 with a small nginx
router that sends each request to the service whose specification declares
that path. The generated tests are NOT modified: they still call
http://127.0.0.1, and the same routing applies to every mode.

The routing table is built from ir.json (the same specifications the model
was given), not written by hand. A path prefix declared by more than one
service (typically /health) cannot be routed unambiguously; it is answered
with a 404 that names the router, so such failures are identifiable as
harness failures in per_test.csv.

USAGE (from the folder containing ir.json, with Sock Shop running)
-----
    python3 router.py up        # stop edge-router, start the test router
    python3 router.py status    # show which entry point is active
    python3 router.py down      # remove the test router, restart edge-router

Every routed response carries an  X-Routed-To: <service>  header.
"""

import argparse
import json
import re
import subprocess
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path

ROUTER_NAME  = "test-router"
NGINX_IMAGE  = "nginx:1.27-alpine"
SERVICE_PORT = 80                       # backend containers listen on 80
CONF_DIR     = Path("router")
CONF_PATH    = CONF_DIR / "nginx.conf"
MAP_PATH     = CONF_DIR / "routes.json"


# ---------------------------------------------------------------------------
# Routing table from ir.json
# ---------------------------------------------------------------------------

def build_routes(ir: dict) -> tuple[dict[str, str], dict[str, list[str]]]:
    """
    Map first path segment -> owning service, from the specs in ir.json.
    Returns (routes, conflicts) where conflicts maps an ambiguous prefix to
    every service that declares it.
    """
    owners: dict[str, set[str]] = {}
    for service, spec in ir["services"].items():
        for ep in spec.get("endpoints", []):
            seg = ep["path"].strip("/").split("/")[0]
            if not seg or seg.startswith("{"):
                continue
            owners.setdefault(seg, set()).add(service)
    routes    = {p: next(iter(s)) for p, s in owners.items() if len(s) == 1}
    conflicts = {p: sorted(s) for p, s in owners.items() if len(s) > 1}
    return routes, conflicts


def nginx_conf(routes: dict[str, str], conflicts: dict[str, list[str]]) -> str:
    blocks = []
    for prefix, service in sorted(routes.items()):
        blocks.append(f"""
    location ~ ^/{re.escape(prefix)}(/|$) {{
      set $up {service};
      add_header X-Routed-To {service} always;
      proxy_pass http://$up:{SERVICE_PORT};
    }}""")
    for prefix, services in sorted(conflicts.items()):
        blocks.append(f"""
    location ~ ^/{re.escape(prefix)}(/|$) {{
      default_type application/json;
      add_header X-Routed-To none always;
      return 404 '{{"router":"ambiguous path, declared by {', '.join(services)}"}}';
    }}""")
    return f"""# Generated by router.py from ir.json. Do not edit by hand.
events {{}}
http {{
  resolver 127.0.0.11 valid=10s ipv6=off;   # Docker's internal DNS
  proxy_read_timeout 60s;
  proxy_http_version 1.1;
  access_log /dev/stdout;

  server {{
    listen 80;

    location = /__router {{
      default_type text/plain;
      return 200 "test-router\\n";
    }}
{''.join(blocks)}

    location / {{
      default_type application/json;
      add_header X-Routed-To none always;
      return 404 '{{"router":"no service declares this path"}}';
    }}
  }}
}}
"""


# ---------------------------------------------------------------------------
# Docker helpers
# ---------------------------------------------------------------------------

def docker(*args: str, check: bool = True) -> str:
    try:
        r = subprocess.run(["docker", *args], capture_output=True, text=True)
    except FileNotFoundError:
        sys.exit("[ERROR] docker not found. Is Docker Desktop running?")
    if check and r.returncode != 0:
        sys.exit(f"[ERROR] docker {' '.join(args)}\n        {r.stderr.strip()}")
    return r.stdout.strip()


def find_container(service: str, include_stopped: bool = False) -> str | None:
    """Container name for a compose service, e.g. docker-compose-catalogue-1."""
    flag = ["-a"] if include_stopped else []
    names = docker("ps", *flag, "--format", "{{.Names}}").splitlines()
    pat = re.compile(rf"(^|[-_]){re.escape(service)}([-_]\d+)?$")
    matches = [n for n in names if pat.search(n)]
    return matches[0] if matches else None


def network_of(container: str) -> str:
    nets = docker("inspect", "-f",
                  "{{range $k, $v := .NetworkSettings.Networks}}{{$k}} {{end}}",
                  container).split()
    if not nets:
        sys.exit(f"[ERROR] could not find the Docker network of {container}")
    return nets[0]


def http_get(path: str) -> tuple[int, str]:
    try:
        with urllib.request.urlopen(f"http://127.0.0.1{path}", timeout=5) as r:
            return r.status, r.headers.get("X-Routed-To", "")
    except urllib.error.HTTPError as e:
        return e.code, e.headers.get("X-Routed-To", "")
    except Exception as e:  # noqa: BLE001
        return 0, type(e).__name__


# ---------------------------------------------------------------------------
# Commands
# ---------------------------------------------------------------------------

def cmd_up(ir_path: str):
    ir = json.loads(Path(ir_path).read_text())
    routes, conflicts = build_routes(ir)
    if not routes:
        sys.exit("[ERROR] no routable paths found in ir.json")

    CONF_DIR.mkdir(exist_ok=True)
    CONF_PATH.write_text(nginx_conf(routes, conflicts))
    MAP_PATH.write_text(json.dumps(
        {"routes": routes, "ambiguous": conflicts}, indent=2))

    print("[ROUTER] Routing table (from ir.json):")
    for p, s in sorted(routes.items()):
        print(f"           /{p:<14} -> {s}")
    for p, s in sorted(conflicts.items()):
        print(f"           /{p:<14} -> AMBIGUOUS ({', '.join(s)}): returns 404")

    probe = find_container("catalogue")
    if not probe:
        sys.exit("[ERROR] catalogue container is not running. Start Sock Shop first.")
    network = network_of(probe)

    edge = find_container("edge-router")
    if edge:
        print(f"[ROUTER] Stopping {edge}")
        docker("stop", edge)

    docker("rm", "-f", ROUTER_NAME, check=False)
    print(f"[ROUTER] Starting {ROUTER_NAME} on port 80 (network {network})")
    docker("run", "-d", "--name", ROUTER_NAME, "--network", network,
           "-p", "80:80",
           "-v", f"{CONF_PATH.resolve()}:/etc/nginx/nginx.conf:ro",
           NGINX_IMAGE)

    for _ in range(20):
        if http_get("/__router")[0] == 200:
            break
        time.sleep(0.5)
    else:
        print(docker("logs", ROUTER_NAME, check=False))
        sys.exit("[ERROR] router did not come up; nginx log above")

    print("[ROUTER] Smoke test:")
    for p, s in sorted(routes.items()):
        code, routed = http_get(f"/{p}")
        print(f"           GET /{p:<14} {code}  routed-to={routed or '-'}")
    print("\n[ROUTER] Up. Status codes other than 0 mean the service answered;")
    print("         a 404/405 here is normal for paths that need an id or POST.")
    print("         Restore the normal setup with:  python3 router.py down")


def cmd_down():
    docker("rm", "-f", ROUTER_NAME, check=False)
    edge = find_container("edge-router", include_stopped=True)
    if edge:
        print(f"[ROUTER] Starting {edge}")
        docker("start", edge)
    print("[ROUTER] Test router removed; edge-router restored.")


def cmd_status():
    if http_get("/__router")[0] == 200:
        print("[ROUTER] Entry point on port 80: TEST ROUTER (direct to services)")
    else:
        code, _ = http_get("/")
        print(f"[ROUTER] Entry point on port 80: edge-router / front-end "
              f"(GET / -> {code})")


def main():
    ap = argparse.ArgumentParser(description="Swap the Sock Shop entry point.")
    ap.add_argument("command", choices=["up", "down", "status"])
    ap.add_argument("--ir", default="ir.json")
    a = ap.parse_args()
    {"up": lambda: cmd_up(a.ir), "down": cmd_down, "status": cmd_status}[a.command]()


if __name__ == "__main__":
    main()
